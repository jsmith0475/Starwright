// Writes js/core/sitesolids.js: the solid shapes of the space centre for the physics (js/core/structures.js), taken
// from the drawing itself (recordSiteSolids in js/render/basegfx.js) plus the Tall Bay beside the Catch Tower
// (js/render/tower.js TOWER_PLAN). tests/unit/structures.test.js fails when the drawing changes and this file was not
// written again:
//   node tests/tools/site_solids.mjs
import { writeFileSync } from 'node:fs';
import { recordSiteSolids, TOWER_SITE } from '../../js/render/basegfx.js';
import { TOWER_PLAN } from '../../js/render/tower.js';

export function siteSolids() {
  const { solids, groups } = recordSiteSolids();
  // the Tall Bay (js/render/tower.js: its body with the roof band, and the low wing on its far side), turned to face the mount
  const b = TOWER_PLAN.bay, yaw = Math.atan2(b.z, -b.x), c = Math.cos(yaw), s = Math.sin(yaw), e = b.w / 2, r2 = v => Math.round(v * 100) / 100 || 0;
  const m = [c, 0, -s, 0, 1, 0, s, 0, c].map(v => Math.round(v * 1e4) / 1e4 || 0);
  const at = (x, z) => [TOWER_SITE.x + b.x + c * x + s * z, TOWER_SITE.z + b.z - s * x + c * z];
  const n0 = solids.length;
  { const [x, z] = at(0, 0); solids.push(['box', r2(x), r2((b.h - 0.6) / 2), r2(z), r2((b.w + 1.4) / 2), r2((b.h + 0.6) / 2), r2((b.d + 1.4) / 2), m]); }
  { const [x, z] = at(e + 1.2, 0); solids.push(['box', r2(x), r2((b.h - 6) / 2), r2(z), 1.2, r2((b.h - 6) / 2), 10.2, m]); }       // the door frame
  { const [x, z] = at(-e - 6, 4); solids.push(['box', r2(x), 4.7, r2(z), 6.3, 5.3, 12.3, m]); }                                   // the low wing
  groups.bay = [n0, solids.length];
  return { solids, groups };
}

if (import.meta.url === 'file://' + process.argv[1]) {
  const { solids, groups } = siteSolids();
  const text = `// GENERATED by tests/tools/site_solids.mjs from the space centre's drawing (js/render/basegfx.js recordSiteSolids,
// js/render/tower.js TOWER_PLAN). Do not edit: change the drawing and run the tool again.
// Shapes in the launch pad's frame (metres, +X east, +Y up from the ground, +Z south), as recordSiteSolids describes:
//   ['box', cx, cy, cz, hx, hy, hz, axes?]  ['cap', ax, ay, az, bx, by, bz, r]  ['cyl', x, y0, z, r, h]  ['sph', x, y, z, r, sy]
export const SITE_GROUPS = ${JSON.stringify(groups)};
export const SITE_SOLIDS = [
${solids.map(s => '  ' + JSON.stringify(s)).join(',\n')},
];
`;
  writeFileSync(new URL('../../js/core/sitesolids.js', import.meta.url), text);
  console.log('js/core/sitesolids.js:', solids.length, 'shapes,', text.length, 'bytes');
}
