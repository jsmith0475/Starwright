//   wing: { area, control: false|'pitch'|'roll'|'yaw'|'auto', sweep? }   on shape 'wing' | 'elevon' | 'tailfin'
//         (radial; rw = span outward, h = root chord along the stack axis, t = thickness)
//   wheel: { radius, drive, brake, steer, maxSpeed, elecUse, retract? }  on shape 'wheel'
//   engine.type: 'liquid' | 'solid' | 'ion' (res xenon + engine.elecUse) | 'nuclear' | 'jet' (engine.jet = { maxAlt, maxMach })
//   res.xenon (kg); light: { range }; shapes 'fuselage', 'cockpit', 'intake', 'rover_body', 'ladder', 'light'
// Cosmetic / optional extras (physics may ignore them; listed in docs/PARTS_TECH.md):
//   variant: string            mesh style hint, read only by js/render/partmesh.js
//   solar.fixed: true          a panel that needs no deploying; antenna.range (m); rcs.linear: true (one nozzle)
//   generator: { rate, fuelUse? }   EC/s made continuously (isotope cell) or while burning fuel kg/s (fuel cell)
//   airbrake: { area }         extra drag area in m² while deployed
//   multi: { count, radius }   engine mounts drawn under a multi-coupler (it attaches like a plain adapter)
// Round-2 additions:
//   capPhi: degrees            the bottom face is a spherical cap of this half-angle (heat shields and tapered
//                              capsules default to 25; 0 = flat). Used above the speed of sound (js/core/aero.js).
//   comY: metres               the part's centre of mass sits this far along its own axis from its centre (negative =
//                              toward the bottom node). Capsules carry it so they float and fall blunt end first.
//                              Craft.centerOfMass() honours it; vessel.js should too (see the assembly hand-back).
//   lab: { rate, mult, elecUse }   science lab: processing rate (× TUNING.LAB_RATE), bonus multiplier, EC/s while working
//   attach.surface on wings and tail fins (WING): surface parts may mount on them
//   shape 'pylon' (attach.outer without a decoupler): a fixed hardpoint; a stack part (a jet, a pod, a tank) mounts
//   on its outer face exactly like a booster on a radial clamp, shares fuel with the craft and never separates.
// Methane and oxygen (docs/SHEARWATER.md):
//   res.lox, res.ch4 (kg)      two real liquids. An engine with engine.prop: 'methalox' burns them together in the
//                              proportion PROP_MIX.methalox (3.6 to 1 by mass) and stops when either runs out.
//   engine.rings: [{ n, thrust (kN, vacuum, EACH engine), ispVac, ispAtm, gimbal }]   a cluster drawn bell by bell
//   engine.modes: [{ name, rings: [ring indices lit] }]   which rings burn; mode 0 is every ring, and engine.thrust,
//                              ispVac, ispAtm and gimbal are the totals of mode 0 so nothing else needs to know.
//   joint: 2                   end rings this many times as strong as a plain part's (structure.js)
//   decoupler.hot: true        a hot-staging ring: it lets go of the stage above and stays on the stage below
//   shape 'flap' (flap: { area, where: 'fore' | 'aft' })   a body flap; it is drawn and weighed, and does not steer yet
// Interstage trusses (not a catalog part; see the helpers at the bottom of this file and Craft.interstages()):
//   whatever is stacked on the nozzle end of a rocket engine is joined to the engine's mount ring by an open
//   lattice ring that surrounds the engine, so the load runs rim to rim and never through the bell. The truss
//   belongs to the part under the engine (usually a separator), weighs INTERSTAGE.kgPerM2 of its wall and leaves
//   with that part when the stack splits.

